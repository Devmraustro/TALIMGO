/** Exposed for the automated localisation-coverage check in src/accessibility.test.tsx. */
export const STRINGS = strings;

export type StringKey = keyof (typeof strings)["en"];

export function translator(locale: Locale) {
  return (key: StringKey, values: Record<string, string | number> = {}): string => {
    const template: string = strings[locale][key] ?? strings.en[key] ?? key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template,
    );
  };
}
